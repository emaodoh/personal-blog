-- Run once in the Supabase SQL Editor before configuring the Render variables.

create table if not exists public.articles (
    id bigint generated by default as identity primary key,
    title text not null,
    content text not null,
    summary text not null default '',
    is_published boolean not null default true
);

create table if not exists public.projects (
    id bigint generated by default as identity primary key,
    title text not null,
    slug text not null unique,
    summary text not null default '',
    description text not null default '',
    technologies text not null default '',
    image_url text not null default '',
    demo_url text not null default '',
    repository_url text not null default '',
    is_featured boolean not null default false,
    is_published boolean not null default false
);

create table if not exists public.pages (
    slug text primary key,
    title text not null,
    content text not null default ''
);

create table if not exists public.settings (
    key text primary key,
    value text not null default ''
);

insert into public.pages (slug, title, content) values
    ('home', 'What I do', 'Tell visitors who you are, what you do, and what you build.'),
    ('about', 'About', 'Add your background, interests, and experience here.'),
    ('contact', 'Contact', 'Add a short invitation for visitors to get in touch.')
on conflict (slug) do nothing;

insert into public.settings (key, value) values
    ('site_name', 'Portfolio'), ('owner_name', 'Your Name'), ('role', 'Developer'),
    ('contact_email', ''), ('profile_image_url', ''), ('resume_url', ''),
    ('github_url', ''), ('linkedin_url', '')
on conflict (key) do nothing;

-- The application server uses the service role key; public API roles need no table access.
revoke all on public.articles, public.projects, public.pages, public.settings from anon, authenticated;
grant all on public.articles, public.projects, public.pages, public.settings to service_role;
grant usage, select on all sequences in schema public to service_role;
